"""Aggregate results/<exp>/seed*.json into results/summary.md (mean ± 95% t-CI)."""
from __future__ import annotations

import glob
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))
from src.bitgrad.stats import fmt_pct, mean_ci  # noqa: E402

RESULTS = os.path.join(os.path.dirname(__file__), "..", "results")


def main():
    rows = []
    for exp_dir in sorted(glob.glob(os.path.join(RESULTS, "*"))):
        if not os.path.isdir(exp_dir) or os.path.basename(exp_dir) == "smoke":
            continue
        runs = [json.load(open(p)) for p in sorted(glob.glob(os.path.join(exp_dir, "seed*.json")))]
        if not runs:
            continue
        finals = [r["final_acc"] for r in runs]
        bests = [r["best_acc"] for r in runs]
        mu_f, _, ci_f = mean_ci(finals)
        mu_b, _, ci_b = mean_ci(bests)
        r0 = runs[0]
        rows.append({
            "exp": os.path.basename(exp_dir),
            "seeds": len(runs),
            "final": fmt_pct(mu_f, ci_f),
            "best": fmt_pct(mu_b, ci_b),
            "state_bits": r0["train_state_bits_per_weight"],
            "infer_bits": r0["inference_weight_bits"],
            "params": r0["n_params_binary_layers"] + r0["n_params_other"],
            "sps": f"{sum(r['steps_per_sec'] for r in runs) / len(runs):.1f}",
        })

    lines = [
        "# Results summary",
        "",
        "Accuracy is test-set %, mean ± 95% t-interval over seeds. `state_bits` =",
        "training state bits per binary-layer weight (weight storage + optimizer",
        "state); `infer_bits` = weight precision at inference. Generated by",
        "`python3 -m experiments.aggregate`.",
        "",
        "| experiment | seeds | final acc | best acc | state_bits/w | infer bits | params | steps/s |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(f"| {r['exp']} | {r['seeds']} | {r['final']} | {r['best']} | "
                     f"{r['state_bits']} | {r['infer_bits']} | {r['params']:,} | {r['sps']} |")
    out = os.path.join(RESULTS, "summary.md")
    os.makedirs(RESULTS, exist_ok=True)
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
